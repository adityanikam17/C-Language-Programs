
//Increment And Decrement operator

#include<stdio.h>

int main()
{
    int a=5, b=10;
    a++;                                       // Post Increament operator (a++)
    printf("Value of A is : %d ",a); 
    //printf("\nValue of A is : %d", ++a);         // Pre Increament operator (++a)

    b--;                                       // Post Decreament operator (--b)
    printf("\nValue of B is : %d", b);
    //printf("\n Value of B is : %d", --b);      // Pre Decreament operator (--b)





    return 0;
}